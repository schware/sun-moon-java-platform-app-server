-- 줄마다 주방 (업무 정의서 §4.4.2)
--
-- 주문 하나가 두 주방에 걸칠 수 있습니다 — 중식과 일식을 같이 파는
-- 매장에서 짜장면과 초밥을 함께 시키면 두 주방이 나눠 만듭니다.
--
-- 그전에는 주문 전체에 **첫 줄의 주방**을 붙여 OMS로 보냈습니다. 그래서
-- 첫 메뉴가 kds-02 것이면 짜장면까지 kds-02 로 갔고, kds-01 은 자기
-- 것을 못 봤습니다. 2026-09-18에 매장에서 나온 보고입니다.
--
-- 원장에도 적어 두는 이유: "이 줄이 어느 주방으로 갔나"는 나중에
-- 되짚을 값이고, OMS에 보내고 잊으면 원장만 보고는 알 수 없습니다.
ALTER TABLE app_order_detail ADD COLUMN IF NOT EXISTS kds_device_id TEXT;
