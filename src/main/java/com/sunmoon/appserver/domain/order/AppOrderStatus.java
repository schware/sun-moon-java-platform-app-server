package com.sunmoon.appserver.domain.order;

/**
 * APP 원장에서 본 주문의 상태.
 *
 * <p><b>OMS의 상태와 다른 축입니다.</b> OMS는 매장이 그 일감을 어디까지
 * 처리했는지를 말하고(수락·조리중·조리완료…), 여기는 <b>손님의 요청이
 * 어떻게 됐는지</b>를 말합니다. 손님 화면이 읽는 것은 이쪽입니다.
 *
 * <p>둘을 한 칸으로 합치면 표현할 수 없는 상태가 생깁니다 — OMS에
 * 넣지도 못한 주문(SEND_FAILED)은 OMS 쪽 상태값이 아예 없고, 그런
 * 주문이야말로 재처리 대상이라 가장 잘 보여야 합니다 (§4.4.6).
 */
public enum AppOrderStatus {

    /** 받아서 원장에 적었습니다. 아직 OMS로 보내기 전. */
    CREATED,
    /**
     * 결제가 거절됐습니다 (§4.10).
     *
     * <p>OMS로 <b>가기 전에</b> 끝난 주문입니다. 거절({@link #REJECTED})과
     * 갈라야 하는 이유: 저쪽은 매장이 안 받은 것이고 이쪽은 돈이 안 된
     * 것이라, 손님이 할 일이 다릅니다 — 하나는 다른 매장을 찾고 하나는
     * 다른 카드를 냅니다.
     */
    PAYMENT_FAILED,
    /** OMS가 접수했습니다. 여기서부터 매장의 일이 됩니다. */
    SENT,
    /** OMS가 거절했습니다 — 마감, 결품, 금액 불일치 등. */
    REJECTED,
    /**
     * OMS에 닿지 못했습니다.
     *
     * <p>거절과 갈라야 합니다: 거절은 답을 받은 것이고 이건 못 받은
     * 것입니다. 앞은 손님에게 이유를 말할 수 있고, 뒤는 <b>다시 보내야</b>
     * 하는 건입니다.
     */
    SEND_FAILED,
    /**
     * 손님이 취소했습니다 (§5.2).
     *
     * <p>거절({@link #REJECTED})과 다릅니다: 저쪽은 매장이 안 받은
     * 것이고 이쪽은 손님이 무른 것입니다. 하루를 되짚을 때 합쳐 두면
     * "우리가 못 받은 것"과 "손님이 마음을 바꾼 것"이 한 숫자가 됩니다.
     */
    CANCELLED
}
