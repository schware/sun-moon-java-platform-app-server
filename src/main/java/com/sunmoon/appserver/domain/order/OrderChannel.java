package com.sunmoon.appserver.domain.order;

/**
 * 주문이 <b>어디로 들어왔나</b> (업무 정의서 §4.4.4 "주문 채널과 유입 경로").
 *
 * <p>{@link OrderType} 과 헷갈리기 쉬운데 다른 질문입니다 — 이쪽은
 * 들어온 문이고 저쪽은 나가는 길입니다. QR로 들어온 배달도, APP으로
 * 들어온 매장 식사도 있을 수 있어서 한 칸으로 못 합니다.
 *
 * <p>이 구분이 필요한 이유는 BO의 APP 매출 조회입니다. 지금 그 화면은
 * "테이블 번호가 있는가"로 QR 주문을 짐작하고 있는데, 그건 도착지이지
 * 유입 경로가 아닙니다 — 테이블 없는 QR이 생기는 날 그 짐작이 틀립니다.
 */
public enum OrderChannel {

    /** 손님 앱(또는 웹)의 매장 선택 화면. */
    APP,
    /** 테이블에 붙은 QR. */
    QR,
    /** 배민원·쿠팡이츠 같은 바깥 채널. 아직 들어오는 길이 없습니다. */
    EXTERNAL
}
